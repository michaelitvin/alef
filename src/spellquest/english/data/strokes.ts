// How each Latin letter is written, stroke by stroke, in Andika's shapes (English Spell Quest's letters: single-storey a
// and g, a plain l with no tail). The format is the Hebrew strokes' (../../spellquest/data/strokes.ts), with `script: 'print'`;
// the Latin/Hebrew axis is the alphabet, not the script. Loaded by plain Node: erasable TS only, data only.
//
// Coordinates: the letter's normalized box, origin top-left, on the four lines below: y = TOP (0) on the top line,
// y = BASE (1) on the baseline, MID the dashed middle line, DESC the descender line; x in the same unit, from 0 at the
// letter's left edge to `w`. Each stroke is a polyline, its start point first. The lines are Andika's own: TOP its
// ascender (b d h k l), MID its x-height, DESC its descender; the capitals stand a little below TOP, as in the font.
//
// The paths are the centre lines of Andika's outlines: guide points were snapped to the middle of the font's ink,
// rounded (Chaikin) and checked against the glyph (every stroke inside the ink, the strokes together covering it).
// Stroke order: the US manuscript print (Zaner-Bloser ball-and-stick): top to bottom, left to right; stems are pulled
// down first and a stroke goes back up a stem before an arch or a bowl (b h m n p r u); circles go back (counter-
// clockwise) from the top right (a c d e g o q s, C G O Q S). Dots and crosses (i j, t f) come last, as marks.
// Where US schools differ the letter holds both variants: a d g q as a bowl and then a stem (Zaner-Bloser), or as one
// stroke that goes on from the bowl up the stem and back down (Handwriting Without Tears).
