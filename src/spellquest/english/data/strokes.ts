/** the strokes that are marks (the dots of i and j, the bars of t and f): any order, also after the next letter */
const MARKS: Record<string, number[]> = { i: [1], j: [1], t: [1], f: [1] }
export const isMark = (letter: string, strokeIndex: number): boolean => MARKS[letter]?.includes(strokeIndex) ?? false

export const latinStrokesOf = (letter: string): LetterDef => {
  const d = LATIN_STROKES.find((x) => x.letter === letter)
  if (!d) throw new Error(`no strokes for ${letter}`)
  return d
}
